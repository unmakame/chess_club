CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA club;
SET search_path = club, public;
CREATE TABLE visitor (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK (btrim(name) <> ''),
 email text NOT NULL UNIQUE CHECK (email = lower(email) AND email ~ '^[^ @]+@[^ @]+[.][^ @]+$')
);
CREATE TABLE employee (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK (btrim(name) <> '')
);
CREATE TABLE chess_table (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL UNIQUE CHECK (btrim(code) <> ''), active boolean NOT NULL DEFAULT true
);
CREATE TABLE tariff (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
 hourly_kopecks integer NOT NULL CHECK (hourly_kopecks > 0)
);
CREATE TABLE closed_day (day date PRIMARY KEY, reason text NOT NULL);
CREATE TABLE booking (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 visitor_id bigint NOT NULL REFERENCES visitor, table_id bigint NOT NULL REFERENCES chess_table,
 tariff_id bigint NOT NULL REFERENCES tariff, request_key uuid NOT NULL,
 starts timestamptz NOT NULL, ends timestamptz NOT NULL, hold_until timestamptz NOT NULL,
 price bigint NOT NULL CHECK (price > 0), full_notice interval NOT NULL DEFAULT '2 hours',
 late_percent integer NOT NULL DEFAULT 50 CHECK (late_percent BETWEEN 0 AND 100),
 status text NOT NULL CHECK (status IN ('HOLD','CONFIRMED','IN_USE','EXPIRED','CANCELLED','NO_SHOW','COMPLETED')),
 UNIQUE(visitor_id,request_key), CHECK (ends-starts >= interval '1 hour'),
 CHECK (mod(extract(epoch FROM starts),1800)=0 AND mod(extract(epoch FROM ends),1800)=0),
 EXCLUDE USING gist (table_id WITH =, tstzrange(starts,ends,'[)') WITH &&)
 WHERE (status IN ('HOLD','CONFIRMED','IN_USE'))
);
CREATE TABLE payment (
 id uuid PRIMARY KEY, booking_id bigint NOT NULL REFERENCES booking,
 amount bigint NOT NULL CHECK (amount>0), applied boolean NOT NULL, received_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX payment_applied ON payment(booking_id) WHERE applied;
CREATE TABLE refund (
 payment_id uuid PRIMARY KEY REFERENCES payment, amount bigint NOT NULL CHECK(amount>0),
 requested_at timestamptz NOT NULL DEFAULT now(), settled_at timestamptz
);
CREATE TABLE visit (
 booking_id bigint PRIMARY KEY REFERENCES booking, employee_id bigint NOT NULL REFERENCES employee,
 entered timestamptz NOT NULL, departed timestamptz CHECK(departed>=entered)
);
CREATE TABLE audit (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, entity text NOT NULL, operation text NOT NULL,
 happened_at timestamptz NOT NULL DEFAULT clock_timestamp(), before_row jsonb, after_row jsonb
);
CREATE FUNCTION log_change() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=club,pg_temp AS $$
BEGIN
 INSERT INTO audit(entity,operation,before_row,after_row) VALUES(TG_TABLE_NAME,TG_OP,to_jsonb(OLD),to_jsonb(NEW));
 RETURN NULL;
END $$;
CREATE TRIGGER booking_audit AFTER INSERT OR UPDATE OR DELETE ON booking FOR EACH ROW EXECUTE FUNCTION log_change();
CREATE TRIGGER payment_audit AFTER INSERT OR UPDATE OR DELETE ON payment FOR EACH ROW EXECUTE FUNCTION log_change();

CREATE FUNCTION check_refund() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.amount > (SELECT amount FROM club.payment WHERE id=NEW.payment_id) THEN
  RAISE EXCEPTION 'Возврат превышает оплату';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER refund_limit BEFORE INSERT OR UPDATE ON refund FOR EACH ROW EXECUTE FUNCTION check_refund();
