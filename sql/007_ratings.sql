CREATE VIEW leaderboard AS
WITH current_week AS (
    SELECT date_trunc('week',now() AT TIME ZONE 'Europe/Moscow')::date AS monday
), latest AS (
    SELECT DISTINCT ON (visitor_id) visitor_id,rating,
           CASE WHEN week_start=monday THEN wins ELSE 0 END AS wins
    FROM player_rating CROSS JOIN current_week WHERE week_start<=monday
    ORDER BY visitor_id,week_start DESC
)
SELECT rank() OVER (ORDER BY rating DESC) AS position,v.id,v.name,rating,wins
FROM latest JOIN visitor v ON v.id=visitor_id;
